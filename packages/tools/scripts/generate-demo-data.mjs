// One-shot offline generator for the two committed demo fixtures.
//
// Reads no live data: it calls `synthDemoData` with a hardcoded `DemoGuide`
// (distributions observed from the production dump / live Mollie / open-banking
// on 2026-08-18) and a fixed seed, then writes two committed TypeScript modules:
//   - packages/tools/src/banking/demo/core.ts     → `export const demoCore`
//   - packages/tools/src/banking/demo/banking.ts  → `export const demoBanking`
//
// Both come from the SAME in-memory object, so invoice numbers, `stl-` ids and
// `tr-` ids agree across files. Re-running yields the identical fixture (the
// guide is a constant), which makes `git diff` after a re-run a real check that
// the committed fixtures still match the generator.
//
// Owner is @slimfact/tools (this package): the api consumes `demoCore` via
// `@slimfact/tools/banking/demo/core`, banking-api consumes `demoBanking` via
// `@slimfact/tools/banking/demo/banking`. Run after building this package,
// since it imports the compiled generator:
//
//   pnpm --filter @slimfact/tools build
//   pnpm --filter @slimfact/tools generate:demo

import { writeFileSync } from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'

import { synthDemoData } from '../dist/banking/demo/synth.js'

// Distributions observed 2026-08-18 (dump + live Mollie sample):
// 3 companies, 14 clients; status mix bill 53.4% / receipt 43.8% / paid 1.4% /
// canceled 1.3% / open 0.1%; amount median €87.68; iDEAL-dominant method mix;
// Mollie fee ≈ €0.299 fixed + rounding per iDEAL payment; refund rate ≈ 0.8%;
// settlement span 2024-11 → 2026-08.
const GUIDE = {
  companyCount: 3,
  clientCount: 14,
  numberedInvoiceCount: 50,
  unnumberedInvoiceCount: 150,
  settlementCount: 30,
  settlementPaymentCountRange: [1, 3],
  settlementFeeFixedCents: 29,
  settlementFeeRoundingCents: 1,
  refundRate: 0.008,
  invoiceAmountMedianCents: 8768,
  invoiceAmountMaxCents: 200000,
  amountSigma: 1.5,
  methodMix: { ideal: 0.8, creditcard: 0.2, banktransfer: 0.0, cash: 0.0 },
  invoiceStatusMix: {
    bill: 0.534,
    receipt: 0.438,
    paid: 0.014,
    canceled: 0.013,
    open: 0.001
  },
  dateRange: { from: '2024-11-01', to: '2026-08-18' }
}

const FIXED_SEED = 0x9e3779b9

const demoDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/banking/demo'
)

const data = synthDemoData(GUIDE, FIXED_SEED)

const header = (pkg) =>
  `// GENERATED by packages/tools/scripts/generate-demo-data.mjs — do not edit.\n` +
  `// Synthetic demo data for ${pkg}; regenerate with \`pnpm --filter @slimfact/tools generate:demo\`.\n`

writeFileSync(
  path.join(demoDir, 'core.ts'),
  `${header('the api seed:fake')}export const demoCore = ${JSON.stringify(data.core, null, 2)} as const\n`
)
writeFileSync(
  path.join(demoDir, 'banking.ts'),
  `${header('the banking-api seed:demo')}export const demoBanking = ${JSON.stringify(data.banking, null, 2)} as const\n`
)

console.log(
  `[generate:demo] wrote demoCore (${data.core.invoices.length} invoices, ${data.core.payments.length} payments, ${data.core.refunds.length} refunds) and demoBanking (${data.banking.pspSettlements.length} settlements, ${data.banking.pspPayments.length} psp payments)`
)
